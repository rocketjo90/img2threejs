"""Generate a replaceable current snapshot, without rewriting review history or granting passes."""
from __future__ import annotations

import hashlib
import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any


def write_project_status(directory: Path, state_status: dict[str, Any], *,
                         spec: dict[str, Any] | None = None, spec_path: Path | None = None) -> dict[str, Any]:
    spec = spec or {}
    history = [item for item in spec.get("reviewHistory", []) if isinstance(item, dict)]
    latest: dict[str, Any] = {}
    for item in history:
        if isinstance(item.get("passId"), str):
            latest[item["passId"]] = item
    payload = {
        "schemaVersion": 1,
        "generatedAt": datetime.now(timezone.utc).isoformat(),
        "target": spec.get("targetName"),
        "specSha256": hashlib.sha256(spec_path.read_bytes()).hexdigest() if spec_path and spec_path.is_file() else None,
        "workflow": state_status,
        "latestRecordedReviews": latest,
        "limitations": ["Recorded reviews are history, not a fresh visual or packaging validation.",
                        "A geometry checkpoint does not complete deferred appearance or delivery work."],
    }
    directory.mkdir(parents=True, exist_ok=True)
    json_path = directory / "current-status.json"
    md_path = directory / "CURRENT_STATUS.md"
    pending = state_status.get("pending", [])
    deferred = state_status.get("deferred", [])
    lines = ["# Current reconstruction status", "", "Generated by forge/next.py; do not hand-edit. Keep decisions in project notes.", "",
             f"- Updated: {payload['generatedAt']}", f"- Target: {payload['target'] or 'not authored'}",
             f"- Spec SHA-256: {payload['specSha256'] or 'not available'}",
             f"- Workflow: {state_status.get('status')}",
             f"- Current pass: {state_status.get('currentPass') or 'pre-spec'}",
             f"- Current step: {state_status.get('currentStep')}",
             f"- Stop reason: {state_status.get('stopReason') or 'none recorded'}",
             f"- Next: {state_status.get('nextCommand') or 'none'}", "", "## Pending work", ""]
    lines += [f"- {step}" + (" (deferred until appearance)" if step in deferred else "") for step in pending] or ["None recorded."]
    lines += ["", "## Latest recorded actions", ""]
    lines += [f"- {pass_id}: {review.get('action', 'unrecorded')}" for pass_id, review in latest.items()] or ["No reviews recorded."]
    lines += ["", *payload["limitations"], ""]
    # A reader never sees half-written JSON/Markdown. Only these generated files are replaced.
    for path, content in ((json_path, json.dumps(payload, indent=2, ensure_ascii=False) + "\n"),
                          (md_path, "\n".join(lines))):
        temporary = path.with_suffix(path.suffix + ".tmp")
        temporary.write_text(content, encoding="utf-8")
        temporary.replace(path)
    return payload
